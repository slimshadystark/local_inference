// NativeLicenses: the native libraries' license texts, one entry per component of local_inference's
// NATIVE_LICENSES.txt, and their registration with Flutter's LicenseRegistry (once, however often it is called).
// The generated constants against the file: tool/embed_native_licenses.dart's --check, in memory.
import 'dart:convert';
import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:local_inference_flutter/local_inference_flutter.dart';

import '../../tool/embed_native_licenses.dart' as embed;

void main() {
  final file = File(embed.source);
  final text = file.readAsStringSync();
  // The sections, read here without the generator: what lies between the lines of `=`.
  final sections = [for (final part in text.split(RegExp(r'\n={20,}\n')).skip(1)) part.trim()];
  const packages = [
    ['llama.cpp', 'ggml'],
    ['llamadart-native'],
    ['nlohmann/json'],
    ['cpp-httplib'],
    ['stb_image'],
    ['rotate-bits'],
    ['SHA-256', 'subprocess.h', 'miniaudio'],
    ['KleidiAI'],
    ['ggml'],
    ['YaRN'],
  ];

  group('the entries', () {
    test('one per section of NATIVE_LICENSES.txt, in its order, its text verbatim, with its package names', () {
      expect(sections, hasLength(10));
      expect([for (final entry in NativeLicenses.entries) entry.packages], packages);
      expect([for (final entry in NativeLicenses.entries) (entry as LicenseEntryWithLineBreaks).text], sections);
    });

    test(
      'each keeps its copyright line and its license: MIT with its permission notice, Apache-2.0, public domain',
      () {
        String paragraphs(int i) => [for (final p in NativeLicenses.entries[i].paragraphs) p.text].join('\n');
        const copyrights = {
          0: 'Copyright (c) 2023-2026 The ggml authors',
          1: 'Copyright (c) 2024 Jhin Lee',
          2: 'Copyright (c) 2013-2025 Niels Lohmann',
          3: 'Copyright (c) 2017 yhirose',
          5: 'Copyright (c) 2021 William Casarin <jb55@jb55.com>',
          8: 'Copyright 2025-2026 Arm Limited and/or its affiliates <open-source-office@arm.com>',
          9: 'Copyright (c) 2023 Jeffrey Quesnelle and Bowen Peng',
        };
        for (final MapEntry(key: i, value: copyright) in copyrights.entries) {
          final text = paragraphs(i);
          expect(text.split('\n'), contains(copyright), reason: '${packages[i]}: a paragraph of its own');
          expect(text, contains('MIT License'), reason: '${packages[i]}');
          expect(text, contains('Permission is hereby granted, free of charge'), reason: '${packages[i]}');
          expect(text, contains('The above copyright notice and this permission notice shall be included'));
        }
        expect(paragraphs(4), contains('ALTERNATIVE A - MIT License Copyright (c) 2017 Sean Barrett'));
        expect(paragraphs(4), contains('ALTERNATIVE B - Public Domain (www.unlicense.org)'));
        expect(paragraphs(6), contains('"2010-06-11 : Igor Pavlov : Public domain"'));
        expect(paragraphs(7), contains('Apache License Version 2.0, January 2004'));
        expect(paragraphs(7), contains('Arm Limited and/or its affiliates <open-source-office@arm.com>'));
        expect(paragraphs(7), contains('END OF TERMS AND CONDITIONS'));
        for (final (i, entry) in NativeLicenses.entries.indexed) {
          expect(entry.paragraphs.first.text, startsWith('${i + 1}. '), reason: 'the section heading comes first');
        }
      },
    );
  });

  group('tool/embed_native_licenses.dart', () {
    test('lib/src/notices/native_licenses.g.dart is what it writes from NATIVE_LICENSES.txt (its --check)', () {
      expect(
        File(embed.target).readAsStringSync(),
        embed.render(file.readAsBytesSync()),
        reason: 'run dart run tool/embed_native_licenses.dart in packages/local_inference_flutter',
      );
    });

    test('the generated file names its source, with its size and SHA-256', () {
      expect(
        File(embed.target).readAsStringSync(),
        startsWith(
          '// GENERATED by tool/embed_native_licenses.dart from ../local_inference/NATIVE_LICENSES.txt: do not edit.\n',
        ),
      );
      expect(
        File(embed.target).readAsStringSync(),
        contains('// NATIVE_LICENSES.txt: ${file.lengthSync()} bytes, sha256 '),
      );
    });

    test('it refuses a section it has no package names for, another heading, a missing section, and a text a raw '
        'string cannot hold', () {
      final separator = '\n\n${'=' * 118}\n\n';
      Matcher refuses(String message) =>
          throwsA(isA<FormatException>().having((e) => e.message, 'message', contains(message)));
      String render(String changed) => embed.render(utf8.encode(changed));
      expect(
        () => render('$text${separator}11. Another library: LICENSE\n\nMIT License\n'),
        refuses('section 11 ("11. Another library: LICENSE") has no package names'),
      );
      expect(
        () => render(text.replaceFirst('4. cpp-httplib:', '4. httplib:')),
        refuses('section 4 starts "4. httplib: vendor/cpp-httplib/LICENSE", not "4. cpp-httplib:"'),
      );
      expect(() => render(text.substring(0, text.lastIndexOf(separator))), refuses('has 9 sections, not the 10'));
      expect(() => render(text.replaceFirst('Igor Pavlov : Public', "Igor Pavlov ''' Public")), refuses("holds '''"));
      expect(() => render(text.replaceAll('\n', '\r\n')), refuses('carriage return'));
      expect(() => embed.render([0xC3, 0x28]), refuses('is not UTF-8'));
    });
  });

  group('registration', () {
    test('the plugin names NativeLicenses as its Dart class on every platform; Android, iOS and macOS also have its '
        'native class, Linux and Windows none', () {
      final pubspec = File('pubspec.yaml').readAsStringSync();
      // A key of the platform's block on a line of its own: a commented-out one does not count.
      Matcher key(String line) => matches(RegExp('^        ${RegExp.escape(line)}\$', multiLine: true));
      for (final platform in ['android', 'ios', 'linux', 'macos', 'windows']) {
        final block = RegExp('^      $platform:\\n((?:        .*\\n)+)', multiLine: true).firstMatch(pubspec)?[1];
        expect(block, key('dartPluginClass: NativeLicenses'), reason: platform);
        final native = key('pluginClass: LocalInferenceFlutterPlugin');
        expect(block, platform == 'linux' || platform == 'windows' ? isNot(native) : native, reason: platform);
      }
    });

    test('registerWith, which the plugin registrant calls, adds the entries to LicenseRegistry; calling it again, or '
        'register, adds nothing', () async {
      // The first registration of this file, and no binding registered licenses before it.
      expect(await LicenseRegistry.licenses.toList(), isEmpty);
      NativeLicenses.registerWith();
      expect(await LicenseRegistry.licenses.toList(), NativeLicenses.entries);
      NativeLicenses.registerWith();
      NativeLicenses.register();
      NativeLicenses.register();
      expect(await LicenseRegistry.licenses.toList(), NativeLicenses.entries);
    });

    testWidgets('showLicensePage lists every component; a package shows its texts', (tester) async {
      NativeLicenses.register();
      tester.view
        ..physicalSize = const Size(800, 2400)
        ..devicePixelRatio = 1;
      addTearDown(tester.view.reset);
      await tester.pumpWidget(
        MaterialApp(
          home: Builder(
            builder: (context) => TextButton(
              onPressed: () => showLicensePage(context: context, applicationName: 'Host app'),
              child: const Text('Licenses'),
            ),
          ),
        ),
      );
      await tester.tap(find.text('Licenses'));
      await tester.pumpAndSettle();
      for (final name in packages.expand((names) => names).toSet()) {
        expect(find.text(name), findsOneWidget, reason: name);
      }
      expect(find.text('2 licenses.'), findsOneWidget, reason: 'ggml: its own, and its KleidiAI glue');
      expect(find.text('1 license.'), findsNWidgets(11));

      await tester.tap(find.text('ggml'));
      await tester.pumpAndSettle();
      expect(find.text('1. llama.cpp and ggml: LICENSE'), findsOneWidget);
      expect(find.text('Copyright (c) 2023-2026 The ggml authors'), findsOneWidget);
      expect(
        find.text('Copyright 2025-2026 Arm Limited and/or its affiliates <open-source-office@arm.com>'),
        findsOneWidget,
      );
      expect(find.text('MIT License'), findsNWidgets(2));
    });
  });
}
