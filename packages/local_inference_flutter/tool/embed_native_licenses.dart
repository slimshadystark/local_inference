// Writes lib/src/notices/native_licenses.g.dart from local_inference's NATIVE_LICENSES.txt: one LicenseEntry per
// component, its section of the file verbatim, with the package names Flutter's license page lists it under. An app
// does not get the files of a package, so the texts go into it as constants.
//
//   dart run tool/embed_native_licenses.dart           # from packages/local_inference_flutter: write the file
//   dart run tool/embed_native_licenses.dart --check   # exit 1, writing nothing, when the file is not up to date
//
// A section that [components] does not name, or a text a raw string cannot hold, stops the generator (exit 1): add
// the new section's package names to [components], then run it again.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

/// NATIVE_LICENSES.txt, from this package's root.
const String source = '../local_inference/NATIVE_LICENSES.txt';

/// The generated file, from this package's root.
const String target = 'lib/src/notices/native_licenses.g.dart';

/// The sections of NATIVE_LICENSES.txt in their order: how the first line of each starts, and its package names.
const List<({String heading, List<String> packages})> components = [
  (heading: '1. llama.cpp and ggml:', packages: ['llama.cpp', 'ggml']),
  (heading: '2. llamadart-native:', packages: ['llamadart-native']),
  (heading: '3. nlohmann/json:', packages: ['nlohmann/json']),
  (heading: '4. cpp-httplib:', packages: ['cpp-httplib']),
  (heading: '5. stb_image ', packages: ['stb_image']),
  (heading: '6. rotate-bits:', packages: ['rotate-bits']),
  (heading: '7. Public domain', packages: ['SHA-256', 'subprocess.h', 'miniaudio']),
  (heading: '8. KleidiAI ', packages: ['KleidiAI']),
  (heading: "9. ggml's KleidiAI glue", packages: ['ggml']),
  (heading: '10. YaRN,', packages: ['YaRN']),
];

/// The sections of [text], the content of NATIVE_LICENSES.txt: what follows each line of `=` (20 or more), up to the
/// next one, without its first and last blank lines. The head of the file, before the first such line, is not one.
List<String> sections(String text) {
  final chunks = <List<String>>[[]];
  for (final line in text.split('\n')) {
    if (RegExp(r'^={20,}$').hasMatch(line)) {
      chunks.add([]);
    } else {
      chunks.last.add(line);
    }
  }
  return [for (final lines in chunks.skip(1)) _withoutBlankEnds(lines)];
}

String _withoutBlankEnds(List<String> lines) {
  var start = 0;
  var end = lines.length;
  while (start < end && lines[start].trim().isEmpty) {
    start++;
  }
  while (end > start && lines[end - 1].trim().isEmpty) {
    end--;
  }
  return lines.sublist(start, end).join('\n');
}

/// The generated file for [bytes], the content of NATIVE_LICENSES.txt.
///
/// Throws [FormatException] when the sections are not those of [components], in order, or one cannot be a raw
/// string.
String render(List<int> bytes) {
  final String text;
  try {
    text = utf8.decode(bytes);
  } on FormatException catch (e) {
    throw FormatException('$source is not UTF-8: ${e.message}');
  }
  if (text.contains('\r')) throw const FormatException('$source holds a carriage return');
  final found = sections(text);
  if (found.length > components.length) {
    throw FormatException(
      '$source: section ${components.length + 1} ("${found[components.length].split('\n').first}") has no '
      'package names; add them to components in tool/embed_native_licenses.dart',
    );
  }
  if (found.length < components.length) {
    throw FormatException('$source has ${found.length} sections, not the ${components.length} of components');
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_native_licenses.dart from $source: do not edit.')
    ..writeln('// Regenerate with `dart run tool/embed_native_licenses.dart` in packages/local_inference_flutter.')
    ..writeln('//')
    ..writeln('// NATIVE_LICENSES.txt: ${bytes.length} bytes, sha256 ${sha256.convert(bytes)}')
    ..writeln()
    ..writeln("import 'package:flutter/foundation.dart';")
    ..writeln()
    ..writeln('/// The sections of NATIVE_LICENSES.txt, verbatim: one entry per component, with its package names.')
    ..writeln('const List<LicenseEntryWithLineBreaks> nativeLicenseEntries = [');
  for (final (i, section) in found.indexed) {
    final (:heading, :packages) = components[i];
    if (!section.startsWith(heading)) {
      throw FormatException('$source: section ${i + 1} starts "${section.split('\n').first}", not "$heading"');
    }
    if (section.contains("'''") || section.endsWith("'")) {
      throw FormatException("$source: section ${i + 1} holds ''' or ends with ', which a raw string cannot hold");
    }
    for (final name in packages) {
      if (!RegExp(r'^[A-Za-z0-9 ._/+-]+$').hasMatch(name)) {
        throw FormatException('components: the package name "$name" needs quoting; use letters, digits and ._/+-');
      }
    }
    // As dart format lays it out; the line break after r''' is not part of the string.
    out
      ..writeln('  LicenseEntryWithLineBreaks(')
      ..writeln("    [${packages.map((name) => "'$name'").join(', ')}],")
      ..writeln("    r'''")
      ..writeln("$section''',")
      ..writeln('  ),');
  }
  out.writeln('];');
  return out.toString();
}

void main(List<String> args) {
  final check = args.contains('--check');
  final unknown = args.where((arg) => arg != '--check').toList();
  if (unknown.isNotEmpty) {
    stderr.writeln('usage: dart run tool/embed_native_licenses.dart [--check] (unknown: ${unknown.join(' ')})');
    exitCode = 2;
    return;
  }
  // The package root: the folder above this script's, else the current one.
  final script = Platform.script;
  final root = script.isScheme('file') && script.path.endsWith('/tool/embed_native_licenses.dart')
      ? File.fromUri(script).parent.parent.path
      : Directory.current.path;
  final String generated;
  try {
    generated = render(File('$root/$source').readAsBytesSync());
  } on FormatException catch (e) {
    stderr.writeln('embed_native_licenses: ${e.message}');
    exitCode = 1;
    return;
  } on FileSystemException catch (e) {
    stderr.writeln('embed_native_licenses: cannot read $source: ${e.message}');
    exitCode = 1;
    return;
  }
  final file = File('$root/$target');
  final current = file.existsSync() ? file.readAsStringSync() : null;
  if (current == generated) {
    stdout.writeln('embed_native_licenses: ok  $target');
  } else if (check) {
    stderr.writeln(
      'embed_native_licenses: DIFFERS  $target (${current == null ? 'missing' : 'not what $source gives'}); '
      'run dart run tool/embed_native_licenses.dart',
    );
    exitCode = 1;
  } else {
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(generated);
    stdout.writeln('embed_native_licenses: wrote  $target');
  }
}
