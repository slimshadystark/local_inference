/// What screen readers say: labels, tooltips, live regions and announcements.
library;

import 'package:flutter/foundation.dart';

/// Accessibility texts in one language: labels, tooltips and announcements.
@immutable
final class A11yStrings {
  const A11yStrings({
    required this.send,
    required this.stop,
    required this.newConversation,
    required this.composerLabel,
    required this.userMessage,
    required this.assistantMessage,
    required this.thinking,
    required this.aiGeneratedHint,
    required this.toolStatus,
    required this.replyAnnouncement,
    required this.jumpToLatest,
    required this.reportAction,
    required this.screenChipHint,
    required this.dismiss,
  });

  /// Italian.
  static const italian = A11yStrings(
    send: 'Invia',
    stop: 'Interrompi',
    newConversation: 'Nuova conversazione',
    composerLabel: 'Messaggio',
    userMessage: 'Tu',
    assistantMessage: _name,
    thinking: 'Sto pensando',
    aiGeneratedHint: "Risposta generata dall'intelligenza artificiale",
    toolStatus: A11yStrings.stripEmoji,
    replyAnnouncement: _announcement,
    jumpToLatest: "Vai all'ultimo messaggio",
    reportAction: 'Segnala risposta',
    screenChipHint: 'Apre la schermata',
    dismiss: 'Chiudi',
  );

  /// English.
  static const english = A11yStrings(
    send: 'Send',
    stop: 'Stop',
    newConversation: 'New conversation',
    composerLabel: 'Message',
    userMessage: 'You',
    assistantMessage: _name,
    thinking: 'Thinking',
    aiGeneratedHint: 'Reply generated by artificial intelligence',
    toolStatus: A11yStrings.stripEmoji,
    replyAnnouncement: _announcement,
    jumpToLatest: 'Jump to the latest message',
    reportAction: 'Report reply',
    screenChipHint: 'Opens the screen',
    dismiss: 'Dismiss',
  );

  /// The send button.
  final String send;

  /// The stop button.
  final String stop;

  /// The new-conversation button.
  final String newConversation;

  /// The composer.
  final String composerLabel;

  /// Who wrote a user message.
  final String userMessage;

  /// Who wrote a reply, from the assistant's name.
  final String Function(String assistantName) assistantMessage;

  /// The live region while the assistant waits for its first text.
  final String thinking;

  /// The hint on model-written replies (machine-readable provenance).
  final String aiGeneratedHint;

  /// A running tool's label as read aloud; the default drops emoji.
  final String Function(String label) toolStatus;

  /// Said when a reply is complete and a screen reader is on.
  final String Function(String assistantName, String reply) replyAnnouncement;

  /// The jump-to-latest button.
  final String jumpToLatest;

  /// The report button.
  final String reportAction;

  /// The hint of a chip that opens a screen.
  final String screenChipHint;

  /// The close button of the dismissible disclosure.
  final String dismiss;

  // Pictographs, skin tones, flags' letters, the emoji variation selector, the zero-width joiner, the keycap mark.
  static const String _emojiPattern =
      r'[\p{Extended_Pictographic}\p{Emoji_Modifier}\p{Regional_Indicator}\u{FE0F}\u{200D}\u{20E3}]';
  static final RegExp _emoji = RegExp(_emojiPattern, unicode: true);

  /// [text] without emoji (pictographs, flags, their modifiers and joiners), so a screen reader does not read them:
  /// "⏳ Cerco gli appuntamenti..." becomes "Cerco gli appuntamenti...".
  static String stripEmoji(String text) => text.replaceAll(_emoji, '').replaceAll(RegExp(r'\s{2,}'), ' ').trim();

  A11yStrings copyWith({
    String? send,
    String? stop,
    String? newConversation,
    String? composerLabel,
    String? userMessage,
    String Function(String assistantName)? assistantMessage,
    String? thinking,
    String? aiGeneratedHint,
    String Function(String label)? toolStatus,
    String Function(String assistantName, String reply)? replyAnnouncement,
    String? jumpToLatest,
    String? reportAction,
    String? screenChipHint,
    String? dismiss,
  }) => A11yStrings(
    send: send ?? this.send,
    stop: stop ?? this.stop,
    newConversation: newConversation ?? this.newConversation,
    composerLabel: composerLabel ?? this.composerLabel,
    userMessage: userMessage ?? this.userMessage,
    assistantMessage: assistantMessage ?? this.assistantMessage,
    thinking: thinking ?? this.thinking,
    aiGeneratedHint: aiGeneratedHint ?? this.aiGeneratedHint,
    toolStatus: toolStatus ?? this.toolStatus,
    replyAnnouncement: replyAnnouncement ?? this.replyAnnouncement,
    jumpToLatest: jumpToLatest ?? this.jumpToLatest,
    reportAction: reportAction ?? this.reportAction,
    screenChipHint: screenChipHint ?? this.screenChipHint,
    dismiss: dismiss ?? this.dismiss,
  );
}

String _name(String assistantName) => assistantName;

String _announcement(String assistantName, String reply) => '$assistantName: ${A11yStrings.stripEmoji(reply)}';
