/// The texts of the chat UI itself: panels, composer, the stale-chip note, the disclosure and the report sheet.
/// Conversation text (replies, questions, Yes and No) comes from the assistant's config, never from here.
library;

import 'package:flutter/foundation.dart';
import 'package:local_inference/local_inference.dart';

import '../compliance/report.dart';

/// Chat texts in one language, [italian] or [english]. Templates are functions, so the packs stay constant;
/// [copyWith] replaces any of them.
@immutable
final class ChatStrings {
  const ChatStrings({
    required this.preparingTitle,
    required this.preparingFirstTime,
    required this.loadFailedTitle,
    required this.loadFailed,
    required this.retry,
    required this.noModelTitle,
    required this.noModelSubtitle,
    required this.refresh,
    required this.notLoadedTitle,
    required this.load,
    required this.composerHint,
    required this.staleScreenRequest,
    required this.thinking,
    required this.detailsGuardedPrefix,
    this.confirmLabel,
    this.declineLabel,
    required this.disclosure,
    required this.report,
    required this.reportTitle,
    required this.reportQuestion,
    required this.reportReason,
    required this.reportCommentHint,
    required this.reportSend,
    required this.reportCancel,
    required this.reportThanks,
    required this.aiGeneratedBadge,
    required this.defaultAssistantName,
  });

  /// Italian.
  static const italian = ChatStrings(
    preparingTitle: "Preparo l'assistente…",
    preparingFirstTime:
        'Solo la prima volta con questo modello: leggo le istruzioni e gli strumenti una volta e le salvo sul '
        'dispositivo.',
    loadFailedTitle: 'Si è verificato un errore',
    loadFailed: _itLoadFailed,
    retry: 'Riprova',
    noModelTitle: 'Nessun modello sul dispositivo',
    noModelSubtitle: 'Aggiungi un modello, poi tocca Aggiorna.',
    refresh: 'Aggiorna',
    notLoadedTitle: 'Il modello non è caricato',
    load: 'Carica',
    composerHint: 'Scrivi un messaggio…',
    staleScreenRequest: "Nel frattempo l'elenco è cambiato: chiedimelo di nuovo in chat.",
    thinking: 'Sto pensando…',
    detailsGuardedPrefix: '⚠︎ risposta sostituita: ',
    disclosure:
        "Le risposte sono generate da un'intelligenza artificiale sul tuo dispositivo e possono contenere "
        'errori.',
    report: 'Segnala risposta',
    reportTitle: 'Segnala questa risposta',
    reportQuestion: 'Che cosa non va?',
    reportReason: _itReportReason,
    reportCommentHint: 'Aggiungi un commento (facoltativo)',
    reportSend: 'Invia',
    reportCancel: 'Annulla',
    reportThanks: 'Grazie: la segnalazione è stata registrata.',
    aiGeneratedBadge: "Generato dall'IA",
    defaultAssistantName: 'Assistente',
  );

  /// English.
  static const english = ChatStrings(
    preparingTitle: 'Preparing the assistant…',
    preparingFirstTime:
        'Only the first time with this model: the instructions and the tools are read once and saved on the device.',
    loadFailedTitle: 'Something went wrong',
    loadFailed: _enLoadFailed,
    retry: 'Try again',
    noModelTitle: 'No model on this device',
    noModelSubtitle: 'Add a model, then tap Refresh.',
    refresh: 'Refresh',
    notLoadedTitle: 'The model is not loaded',
    load: 'Load',
    composerHint: 'Write a message…',
    staleScreenRequest: 'The list has changed in the meantime: ask me again in the chat.',
    thinking: 'Thinking…',
    detailsGuardedPrefix: '⚠︎ answer replaced: ',
    disclosure: 'Replies are generated by an AI running on your device and may contain mistakes.',
    report: 'Report reply',
    reportTitle: 'Report this reply',
    reportQuestion: "What's wrong with it?",
    reportReason: _enReportReason,
    reportCommentHint: 'Add a comment (optional)',
    reportSend: 'Send',
    reportCancel: 'Cancel',
    reportThanks: 'Thank you: the report was recorded.',
    aiGeneratedBadge: 'AI-generated',
    defaultAssistantName: 'Assistant',
  );

  /// The title while a model loads or its prefix state is restored or built.
  final String preparingTitle;

  /// The subtitle while the prefix state is built (the first time with a model).
  final String preparingFirstTime;

  /// The title when the model could not be loaded.
  final String loadFailedTitle;

  /// Why the model could not be loaded. The defaults name the kind of failure, never the raw exception, which the
  /// panel shows under it with `ChatFeatures.showDetails`.
  final String Function(Object error) loadFailed;

  /// The button that loads the model again.
  final String retry;

  /// The panel when there is no model to load.
  final String noModelTitle;
  final String noModelSubtitle;

  /// The button that looks for models again.
  final String refresh;

  /// The panel when a model is there but not loaded, and its button.
  final String notLoadedTitle;
  final String load;

  /// The composer's hint.
  final String composerHint;

  /// The note when a chip's item is no longer the one it named.
  final String staleScreenRequest;

  /// Shown while the assistant waits for the first visible text.
  final String thinking;

  /// Before the details of an answer a guard replaced.
  final String detailsGuardedPrefix;

  /// The confirmation buttons' labels; null uses the assistant's own (its Yes and No), which match the user item a
  /// tap adds.
  final String? confirmLabel;
  final String? declineLabel;

  /// The AI-disclosure text.
  final String disclosure;

  /// The selection-menu entry and the tooltip that report a reply.
  final String report;

  /// The report sheet.
  final String reportTitle;
  final String reportQuestion;
  final String Function(ReportReason reason) reportReason;
  final String reportCommentHint;
  final String reportSend;
  final String reportCancel;

  /// The note after a report was handed to the host.
  final String reportThanks;

  /// The optional mark on model-written replies.
  final String aiGeneratedBadge;

  /// The name used when the host gives none.
  final String defaultAssistantName;

  ChatStrings copyWith({
    String? preparingTitle,
    String? preparingFirstTime,
    String? loadFailedTitle,
    String Function(Object error)? loadFailed,
    String? retry,
    String? noModelTitle,
    String? noModelSubtitle,
    String? refresh,
    String? notLoadedTitle,
    String? load,
    String? composerHint,
    String? staleScreenRequest,
    String? thinking,
    String? detailsGuardedPrefix,
    String? confirmLabel,
    String? declineLabel,
    String? disclosure,
    String? report,
    String? reportTitle,
    String? reportQuestion,
    String Function(ReportReason reason)? reportReason,
    String? reportCommentHint,
    String? reportSend,
    String? reportCancel,
    String? reportThanks,
    String? aiGeneratedBadge,
    String? defaultAssistantName,
  }) => ChatStrings(
    preparingTitle: preparingTitle ?? this.preparingTitle,
    preparingFirstTime: preparingFirstTime ?? this.preparingFirstTime,
    loadFailedTitle: loadFailedTitle ?? this.loadFailedTitle,
    loadFailed: loadFailed ?? this.loadFailed,
    retry: retry ?? this.retry,
    noModelTitle: noModelTitle ?? this.noModelTitle,
    noModelSubtitle: noModelSubtitle ?? this.noModelSubtitle,
    refresh: refresh ?? this.refresh,
    notLoadedTitle: notLoadedTitle ?? this.notLoadedTitle,
    load: load ?? this.load,
    composerHint: composerHint ?? this.composerHint,
    staleScreenRequest: staleScreenRequest ?? this.staleScreenRequest,
    thinking: thinking ?? this.thinking,
    detailsGuardedPrefix: detailsGuardedPrefix ?? this.detailsGuardedPrefix,
    confirmLabel: confirmLabel ?? this.confirmLabel,
    declineLabel: declineLabel ?? this.declineLabel,
    disclosure: disclosure ?? this.disclosure,
    report: report ?? this.report,
    reportTitle: reportTitle ?? this.reportTitle,
    reportQuestion: reportQuestion ?? this.reportQuestion,
    reportReason: reportReason ?? this.reportReason,
    reportCommentHint: reportCommentHint ?? this.reportCommentHint,
    reportSend: reportSend ?? this.reportSend,
    reportCancel: reportCancel ?? this.reportCancel,
    reportThanks: reportThanks ?? this.reportThanks,
    aiGeneratedBadge: aiGeneratedBadge ?? this.aiGeneratedBadge,
    defaultAssistantName: defaultAssistantName ?? this.defaultAssistantName,
  );
}

String _itLoadFailed(Object error) => switch (error) {
  UnsupportedModelException() => "Questo modello non è compatibile con l'assistente.",
  ModelLoadException() => 'Non riesco a caricare il modello: riprova.',
  _ => "Non riesco a preparare l'assistente: riprova.",
};

String _enLoadFailed(Object error) => switch (error) {
  UnsupportedModelException() => 'This model does not work with the assistant.',
  ModelLoadException() => 'The model could not be loaded: try again.',
  _ => 'The assistant could not start: try again.',
};

String _itReportReason(ReportReason reason) => switch (reason) {
  ReportReason.offensive => 'Offensiva o inappropriata',
  ReportReason.wrong => 'Sbagliata o inventata',
  ReportReason.harmful => 'Pericolosa',
  ReportReason.other => 'Altro',
};

String _enReportReason(ReportReason reason) => switch (reason) {
  ReportReason.offensive => 'Offensive or inappropriate',
  ReportReason.wrong => 'Wrong or made up',
  ReportReason.harmful => 'Harmful',
  ReportReason.other => 'Other',
};
