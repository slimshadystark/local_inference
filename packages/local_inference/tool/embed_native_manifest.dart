// Writes lib/src/doctor/native_manifest.g.dart from tool/native/llamadart-native-<tag>.sha256, so the doctor carries
// the manifest wherever the package is (the pub cache, a compiled tool).
//
//   dart run tool/embed_native_manifest.dart           # from packages/local_inference: write the file
//   dart run tool/embed_native_manifest.dart --check   # exit 1 when the file is not up to date
import 'dart:io';

import 'package:path/path.dart' as p;

const tag = 'v0.4.0';

void main(List<String> args) {
  final check = args.contains('--check');
  final package = p.dirname(p.dirname(p.fromUri(Platform.script)));
  final manifest = File(p.join(package, 'tool', 'native', 'llamadart-native-$tag.sha256')).readAsStringSync();
  final target = File(p.join(package, 'lib', 'src', 'doctor', 'native_manifest.g.dart'));
  final generated = render(manifest);
  if (check) {
    final current = target.existsSync() ? target.readAsStringSync() : '';
    if (current != generated) {
      stderr.writeln(
        'embed_native_manifest: ${target.path} is out of date; run dart run tool/embed_native_manifest.dart',
      );
      exitCode = 1;
    } else {
      stdout.writeln('embed_native_manifest: up to date');
    }
    return;
  }
  target.writeAsStringSync(generated);
  stdout.writeln('embed_native_manifest: wrote ${target.path}');
}

String render(String manifest) {
  if (manifest.contains("'''")) throw const FormatException('the manifest cannot hold three quotes');
  return '''
// GENERATED by tool/embed_native_manifest.dart from tool/native/llamadart-native-$tag.sha256; do not edit.

/// The llamadart-native release the manifest covers (llamadart 0.8.23's pin).
const String nativeManifestTag = '$tag';

/// tool/native/llamadart-native-$tag.sha256, verbatim.
const String nativeManifestText = r\'\'\'
$manifest\'\'\';
''';
}
